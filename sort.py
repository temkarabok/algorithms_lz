import random
a = [random.randint(0,1000000) for i in range(100)]#не отсортированный начальный список
b = a.copy()#копия для 2 алгоритма
q = 0 #счетчик перемещений для пузырька
i = 0 #текущий индекс
print("начальный список: ", a)
print("СОРТИРОВКА ПУЗЫРЕК:")
while i<len(a)-1:
    if a[i]<a[i+1]:
        a[i],a[i+1]=a[i+1],a[i]
        q+=1
        i=0
    else:
        i+=1
print("отсортированный список пузырьком: ", a)
print("количество операций: ", q)

w = 0 #счетчик перемещений для выбора
print("СОРТИРОВКА ВЫБОРОМ:")
for j in range(len(b)):
    m=j#индекс максимума
    for k in range(j+1,len(b)):#поиск максимума справа
        if b[k]>b[m]:
            m=k
    if m != j:#если максимум не на месте
        b[j],b[m]=b[m],b[j]
        w+=1#подсчет перемещений
print("отсортированный список выбором: ", b)
print("количество операций: ", w)